export type SoilStatus = "dry" | "intermediate" | "wet" | string;

export interface IrrigationDevice {
  devEUI: string;
  name: string;
}

export interface IrrigationLocation {
  latitude?: number | null;
  longitude?: number | null;
  source?: string;
  timezone?: string;
}

export interface IrrigationSensor {
  air_humidity_percent?: number | null;
  air_temperature_celsius?: number | null;
  soil_moisture_kalman_filtered?: number | null;
  soil_moisture_raw?: number | null;
  timestamp?: string | null;
  validity?: boolean;
}

export interface ForecastDay {
  date: string;
  precipitation_probability_percent?: number | null;
  precipitation_mm?: number | null;
  et0_mm?: number | null;
  rain_likely?: boolean;
}

/** Recommendation and business-rule results are authored by the Go MSS. */
export interface IrrigationRecommendation {
  action?: string;
  message?: string;
  recommended_day?: string | null;
  should_irrigate?: boolean | null;
  should_irrigate_today?: boolean | null;
  soil_status?: SoilStatus;
  rain_probability_percent?: number | null;
  expected_rain_mm?: number | null;
  requires_manual_validation?: boolean;
}

/** Historical readings filtered by the Go MSS (never recalculated by the UI). */
export interface MSSSensorHistoryPoint {
  timestamp: string;
  soil_moisture_raw: number;
  soil_moisture_kalman_filtered: number;
}

export interface SoilMoisturePredictionPoint {
  timestamp: string;
  hours_ahead: number;
  soil_moisture_predicted: number;
  lower_bound: number;
  upper_bound: number;
}

export interface SoilMoistureDiagnostics {
  persistent_zero: boolean;
  sensor_saturated: boolean;
  consecutive_near_zero: number;
  consecutive_near_maximum: number;
  required_consecutive_samples: number;
  messages: string[];
}

/** Full v3 prediction contract generated by the Go MSS. */
export interface SoilMoisturePrediction {
  model: string;
  unit: string;
  base_timestamp: string;
  horizon_hours: number;
  step_minutes: number;
  current_filtered: number;
  trend_per_hour: number;
  trend_status: "increasing" | "decreasing" | "stable" | string;
  predicted_at_horizon: number;
  change_from_current: number;
  prediction_interval_width: number;
  confidence_status: "high_uncertainty" | "within_threshold" | "unavailable" | string;
  diagnostics: SoilMoistureDiagnostics;
  points: SoilMoisturePredictionPoint[];
}

/** Aggregates computed by the Go MSS over the returned weather window. */
export interface ForecastSummary {
  days: number;
  total_precipitation_mm: number;
  max_precipitation_probability_percent: number;
  days_with_likely_rain: number;
  et0_available: boolean;
  total_et0_mm?: number | null;
}

export interface IrrigationResponse {
  sensor_id: string;
  location?: IrrigationLocation;
  sensor?: IrrigationSensor;
  sensor_history?: MSSSensorHistoryPoint[];
  soil_moisture_prediction?: SoilMoisturePrediction;
  forecast_today_and_next_5_days?: ForecastDay[];
  forecast_summary?: ForecastSummary;
  irrigation?: IrrigationRecommendation;
  note?: string;
}
